// FileKit mark: a file sheet with a folded corner, slanted like Inter Bold Italic.
// Pure functions returning SVG markup, shared by the browser templates and the Node export script.

/** Italic angle of Inter Bold Italic (post.italicAngle), so the sheet leans like the "F". */
export const ITALIC_ANGLE = 9.4;
const SLANT = Math.tan((ITALIC_ANGLE * Math.PI) / 180);

const W = 18; // sheet width
const H = 24; // sheet height
const FOLD = 6; // folded corner size
const R = 2.5; // corner radius

const SHEET = `M${R} 0H${W - FOLD}L${W} ${FOLD}V${H - R}A${R} ${R} 0 0 1 ${W - R} ${H}H${R}A${R} ${R} 0 0 1 0 ${H - R}V${R}A${R} ${R} 0 0 1 ${R} 0Z`;
const FOLD_PATH = `M${W - FOLD} 0V${FOLD - 2}A2 2 0 0 0 ${W - FOLD + 2} ${FOLD}H${W}Z`;

const WHITE_FOLD = 'fill="#fff" fill-opacity=".55"';

/** Bounding box of the slanted sheet inside the 32x32 mark box, to crop lockups tightly. */
export const MARK_BOX = { x: (32 - (W + SLANT * H)) / 2, y: (32 - H) / 2, width: W + SLANT * H, height: H };

/**
 * Returns the mark's inner SVG (gradient + shapes) in a 32x32 box.
 * @param {string[]} colors three gradient stops, bottom-left to top-right: deep, mid, highlight
 * @param {string} id unique prefix for the gradient id
 * @param {string} fold fill of the folded corner, translucent white by default
 */
export function markShapes([deep, mid, highlight], id = 'fk', fold = WHITE_FOLD) {
  const x = MARK_BOX.x + SLANT * H; // skewX moves the bottom edge left, so start the top edge further right
  return `<defs><linearGradient id="${id}-g" x1="0" y1="1" x2="1" y2="0">` +
    `<stop stop-color="${deep}"/><stop offset=".55" stop-color="${mid}"/><stop offset="1" stop-color="${highlight}"/>` +
    '</linearGradient></defs>' +
    `<g transform="translate(${x.toFixed(2)} ${MARK_BOX.y}) skewX(${-ITALIC_ANGLE})">` +
    `<path d="${SHEET}" fill="url(#${id}-g)"/>` +
    `<path d="${FOLD_PATH}" ${fold}/>` +
    '</g>';
}

/** Standalone mark SVG document. */
export function markSvg(colors, size = 32, id = 'fk', fold = WHITE_FOLD) {
  return `<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" viewBox="0 0 32 32">${markShapes(colors, id, fold)}</svg>`;
}

/**
 * The mark as an Android vector drawable (also read by Compose Multiplatform resources), in a 32x32 viewport.
 * Vector drawables cannot skew, so the slant is baked into the coordinates and the corner arcs become cubics.
 * @param {string[]} colors three gradient stops, as in markShapes
 * @param {number} size width and height in dp
 */
export function markVectorDrawable([deep, mid, highlight], size = 32) {
  const x0 = MARK_BOX.x + SLANT * H;
  const t = ([x, y]) => [x - SLANT * y + x0, y + MARK_BOX.y];
  // markShapes uses an objectBoundingBox gradient: its isolines run parallel to the sheet's top-left to
  // bottom-right diagonal. Android gradients have isolines perpendicular to start-end, so end on that normal.
  const [sx, sy] = t([0, H]);
  const diagonal = [W - SLANT * H, H];
  const normal = [diagonal[1], -diagonal[0]].map((v) => v / Math.hypot(...diagonal));
  const span = (W + SLANT * H) * normal[0] - H * normal[1]; // projection of start-to-top-right onto the normal
  const [ex, ey] = [sx + normal[0] * span, sy + normal[1] * span];
  const gradient = `<aapt:attr name="android:fillColor"><gradient android:type="linear" android:startX="${f(sx)}" ` +
    `android:startY="${f(sy)}" android:endX="${f(ex)}" android:endY="${f(ey)}">` +
    `<item android:offset="0" android:color="${deep}"/><item android:offset="0.55" android:color="${mid}"/>` +
    `<item android:offset="1" android:color="${highlight}"/></gradient></aapt:attr>`;
  return '<?xml version="1.0" encoding="utf-8"?>\n' +
    '<!-- Generated by brand/render.mjs from brand/src/mark.js. Do not edit. -->\n' +
    '<vector xmlns:android="http://schemas.android.com/apk/res/android" xmlns:aapt="http://schemas.android.com/aapt"\n' +
    `    android:width="${size}dp" android:height="${size}dp" android:viewportWidth="32" android:viewportHeight="32">\n` +
    `    <path android:pathData="${bake(SHEET, t)}">${gradient}</path>\n` +
    `    <path android:pathData="${bake(FOLD_PATH, t)}" android:fillColor="#FFFFFF" android:fillAlpha="0.55"/>\n` +
    '</vector>\n';
}

const f = (n) => Number(n.toFixed(3)).toString();

/**
 * Applies the affine `transform` to an absolute SVG path made of M, L, H, V, Z and quarter-circle A commands.
 * Affine maps keep cubic Béziers exact, so each arc becomes one cubic before the transform.
 */
function bake(d, transform) {
  const out = [];
  const pt = (p) => transform(p).map(f).join(' ');
  let cur = [0, 0];
  for (const [, cmd, args] of d.matchAll(/([MLHVAZ])([^MLHVAZ]*)/g)) {
    const n = args.trim().split(/[\s,]+/).filter(Boolean).map(Number);
    if (cmd === 'M' || cmd === 'L') { cur = [n[0], n[1]]; out.push(`${cmd}${pt(cur)}`); }
    else if (cmd === 'H') { cur = [n[0], cur[1]]; out.push(`L${pt(cur)}`); }
    else if (cmd === 'V') { cur = [cur[0], n[0]]; out.push(`L${pt(cur)}`); }
    else if (cmd === 'Z') out.push('Z');
    else {
      const [r, , , , sweep, x, y] = n;
      const end = [x, y];
      // Center of the quarter circle: off the chord midpoint by r/√2, on the side that matches the sweep.
      const mx = (cur[0] + x) / 2, my = (cur[1] + y) / 2;
      const dx = x - cur[0], dy = y - cur[1];
      const len = Math.hypot(dx, dy);
      const side = sweep ? 1 : -1;
      const c = [mx - (side * dy / len) * (len / 2), my + (side * dx / len) * (len / 2)];
      // Tangents point along the direction of travel; k is the usual cubic approximation of a quarter circle.
      const k = 0.5523 * side;
      const c1 = [cur[0] - k * (cur[1] - c[1]), cur[1] + k * (cur[0] - c[0])];
      const c2 = [x + k * (y - c[1]), y - k * (x - c[0])];
      out.push(`C${pt(c1)} ${pt(c2)} ${pt(end)}`);
      cur = end;
    }
  }
  return out.join('');
}
